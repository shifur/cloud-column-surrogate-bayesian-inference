"""Cross-artifact checks that prevent experimental-domain drift."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Iterable

from cloud_column_reproduction.domain import ParameterBox
from cloud_column_reproduction.provenance import sha256_file, validate_manifest


def audit_manifests(
    manifest_paths: Iterable[str | Path],
    parameter_box: ParameterBox,
    parameter_box_config: str | Path,
    *,
    verify_recorded_config_file: bool = True,
    allow_legacy_schema_v1: bool = False,
) -> list[Path]:
    """Audit registered artifacts and their shared physical domain.

    ``verify_recorded_config_file`` is disabled only when a later experiment
    consumes an immutable data artifact.  In that case, the producing config's
    recorded path may have evolved after generation; the consumer must validate
    the data checksum and embedded artifact-specific contract independently.
    The original config hash remains in the manifest and is never rewritten.

    ``allow_legacy_schema_v1`` is reserved for checksum-valid, immutable input
    data generated by the controlled predecessor pipeline. It does not upgrade
    or rewrite that historical manifest, and all domain, data, and scientific
    artifact checks below remain active.
    """
    paths = [Path(path).resolve() for path in manifest_paths]
    if not paths:
        raise ValueError("At least one artifact manifest is required")
    box_config = Path(parameter_box_config).resolve()
    expected_file_hash = sha256_file(box_config)
    repository = box_config.parent.parent
    errors: list[str] = []
    for path in paths:
        payload = json.loads(path.read_text(encoding="utf-8"))
        legacy_schema_v1 = (
            allow_legacy_schema_v1 and payload.get("manifest_schema_version") == 1
        )
        if legacy_schema_v1:
            required_legacy = {
                "run_id", "created_utc", "status", "command", "git",
                "scientific_source_snapshot", "environment", "artifact",
                "config", "config_sha256", "parameter_box_sha256",
                "parameter_box_config", "parameter_box_config_sha256",
                "random_seeds", "workers", "wall_seconds",
            }
            missing_legacy = sorted(required_legacy.difference(payload))
            if missing_legacy:
                errors.append(
                    f"{path}: legacy manifest is missing required fields: "
                    + ", ".join(missing_legacy)
                )
            if payload.get("status") != "complete":
                errors.append(f"{path}: legacy input artifact is not complete")
            snapshot = payload.get("scientific_source_snapshot", {})
            if not isinstance(snapshot, dict) or not snapshot.get("sha256"):
                errors.append(f"{path}: legacy scientific-source snapshot is incomplete")
            environment = payload.get("environment", {})
            if (
                not isinstance(environment, dict)
                or not isinstance(environment.get("path"), str)
                or not isinstance(environment.get("sha256"), str)
            ):
                errors.append(f"{path}: legacy environment record is incomplete")
        else:
            try:
                validate_manifest(payload)
            except ValueError as error:
                errors.append(f"{path}: {error}")
            environment = payload.get("environment", {})
            environment_name = (
                environment.get("specification")
                if isinstance(environment, dict) else None
            )
            environment_hash = (
                environment.get("specification_sha256")
                if isinstance(environment, dict) else None
            )
            if (
                not isinstance(environment_name, str)
                or not isinstance(environment_hash, str)
            ):
                errors.append(
                    f"{path}: environment specification path/checksum is missing"
                )
            else:
                environment_path = repository / environment_name
                if (
                    not environment_path.is_file()
                    or sha256_file(environment_path) != environment_hash
                ):
                    errors.append(
                        f"{path}: environment specification checksum mismatch"
                    )
        if payload.get("parameter_box_sha256") != parameter_box.fingerprint:
            errors.append(f"{path}: parameter-box content fingerprint mismatch")
        if payload.get("parameter_box_config_sha256") != expected_file_hash:
            errors.append(f"{path}: parameter-box config checksum mismatch")
        config_name = payload.get("config")
        config_hash = payload.get("config_sha256")
        if not isinstance(config_name, str) or not isinstance(config_hash, str):
            errors.append(f"{path}: experiment config path/checksum is missing")
        elif verify_recorded_config_file:
            config_path = repository / config_name
            if not config_path.is_file() or sha256_file(config_path) != config_hash:
                errors.append(f"{path}: experiment config checksum mismatch")
        data_name = payload.get("data_file")
        data_hash = payload.get("data_sha256")
        if isinstance(data_name, str) and isinstance(data_hash, str):
            data_path = path.parent / data_name
            if not data_path.is_file() or sha256_file(data_path) != data_hash:
                errors.append(f"{path}: data artifact checksum mismatch")
        if payload.get("artifact") in {
            "figure1-primary-evaluation-inputs",
            "figure1-primary-evaluation-data",
            "figure1-monte-carlo-diagnostic-inputs",
            "figure1-monte-carlo-diagnostic-data",
        }:
            if payload.get("metric") != "equal-weight-relative-l2":
                errors.append(f"{path}: Monte Carlo artifact does not use equal-weight L2")
        if payload.get("artifact") in {
            "figure1-primary-rqmc-inputs",
            "figure1-primary-rqmc-evaluation-data",
        }:
            if payload.get("metric") != "replicated-rqmc-relative-l2":
                errors.append(f"{path}: primary evaluation is not replicated RQMC")
            if payload.get("weight_policy") != "equal-positive":
                errors.append(f"{path}: RQMC weights are not equal and positive")
            if payload.get("metric_status") != "primary-figure1-error-metric":
                errors.append(f"{path}: RQMC metric is not marked primary")
            construction = payload.get("rqmc_construction", {})
            if construction.get("randomization") != "NUS":
                errors.append(f"{path}: RQMC does not use nested uniform scrambling")
        if payload.get("artifact") in {
            "figure1-sparse-grid-reference",
            "figure1-sparse-grid-reference-data",
            "figure1-primary-sparse-grid-inputs",
            "figure1-primary-sparse-grid-evaluation-data",
            "figure1-secondary-sparse-grid-inputs",
            "figure1-secondary-sparse-grid-evaluation-data",
        }:
            if payload.get("corrected_weight_policy") != "signed-quadrature":
                errors.append(f"{path}: sparse-grid weights are not preserved as signed")
        if payload.get("artifact") in {
            "figure1-secondary-sparse-grid-inputs",
            "figure1-secondary-sparse-grid-evaluation-data",
        }:
            construction = payload.get("tasmanian_construction", {})
            if construction.get("rule") != "gauss-patterson":
                errors.append(f"{path}: secondary sparse grid is not Gauss-Patterson")
            if construction.get("depth_type") != "level":
                errors.append(f"{path}: secondary sparse grid must not use qptotal")
            if payload.get("metric_status") != "secondary-sparse-grid-adequacy-check":
                errors.append(f"{path}: sparse-grid metric is not marked secondary")
        if payload.get("artifact") in {
            "figure1-primary-sparse-grid-inputs",
            "figure1-primary-sparse-grid-evaluation-data",
        }:
            if payload.get("metric") != "signed-quadrature-relative-l2":
                errors.append(f"{path}: primary evaluation is not signed quadrature")
            if payload.get("metric_status") != "primary-figure1-error-metric":
                errors.append(f"{path}: sparse-grid metric is not marked primary")
        if payload.get("artifact", "").startswith("figure1-"):
            for field in ("random_seeds", "workers", "wall_seconds"):
                if field not in payload:
                    errors.append(f"{path}: required run field {field!r} is missing")
        if payload.get("sccm_executable") is not None:
            for field in (
                "sccm_executable_sha256",
                "sccm_namelist_sha256",
                "sccm_rendered_namelist_sha256",
                "sccm_radiation_table_sha256",
            ):
                if not payload.get(field):
                    errors.append(f"{path}: required SCCM field {field!r} is missing")
    if errors:
        raise ValueError("Pipeline invariant audit failed:\n" + "\n".join(errors))
    return paths
